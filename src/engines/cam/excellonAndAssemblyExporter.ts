import { PcbProject, Point2D } from '../../core/types';
import { getWorldPads } from '../drc';

/** Generates an Excellon N/C Drill (.drl) file in METRIC,TZ mode. */
export function exportExcellonDrill(pcb: PcbProject): string {
  const drills = new Map<string, Point2D[]>();
  const addDrill = (dia: number, pt: Point2D) => {
    const key = dia.toFixed(3);
    if (!drills.has(key)) drills.set(key, []);
    drills.get(key)!.push(pt);
  };

  for (const wp of getWorldPads(pcb)) {
    if ((wp.pad.type === 'THT' || wp.pad.type === 'MountingHole') && (wp.pad.holeDiameter ?? 0) > 0) {
      addDrill(wp.pad.holeDiameter!, { x: wp.x, y: wp.y });
    }
  }
  for (const v of pcb.vias) {
    addDrill(v.holeDiameter, { x: v.x, y: v.y });
  }

  const lines: string[] = [
    '; Excellon N/C Drill generated by GOSTTrace EDA (ГОСТ-Трейс)',
    'M48',
    'METRIC,TZ'
  ];

  const tools = Array.from(drills.entries());
  tools.forEach(([dia], i) => {
    lines.push(`T${String(i + 1).padStart(2, '0')}C${dia}`);
  });
  lines.push('%');
  lines.push('G90');
  lines.push('G05');

  tools.forEach(([, pts], i) => {
    lines.push(`T${String(i + 1).padStart(2, '0')}`);
    for (const pt of pts) {
      lines.push(`X${pt.x.toFixed(3)}Y${pt.y.toFixed(3)}`);
    }
  });
  lines.push('M30');
  return lines.join('\n');
}

/** Exports component placement Pick-and-Place CSV (UTF-8 BOM, semicolon-delimited). */
export function exportPickAndPlaceCsv(pcb: PcbProject): string {
  const lines = ['RefDes;Value;Pattern;Side;X(mm);Y(mm);Rotation(deg)'];
  for (const c of pcb.components) {
    lines.push(`${c.refDes};"${c.value}";"${c.patternId}";${c.side};${c.x.toFixed(3)};${c.y.toFixed(3)};${c.angle}`);
  }
  return '\uFEFF' + lines.join('\n');
}

/** Exports an IPC-D-356 bare-board test netlist file. */
export function exportIpcD356(pcb: PcbProject): string {
  const lines = [
    'C  IPC-D-356 Netlist generated by GOSTTrace EDA',
    'P  UNITS CUST 0',
    'P  JOB   ' + pcb.projectName
  ];
  for (const wp of getWorldPads(pcb)) {
    const net = (wp.netName || 'N/C').slice(0, 14).padEnd(14, ' ');
    const ref = wp.refDes.slice(0, 6).padEnd(6, ' ');
    const pin = wp.pad.number.slice(0, 4).padEnd(4, ' ');
    const xMil = Math.round((wp.x / 25.4) * 10000);
    const yMil = Math.round((wp.y / 25.4) * 10000);
    lines.push(`317${net} ${ref}-${pin}  X${xMil >= 0 ? '+' : ''}${xMil}Y${yMil >= 0 ? '+' : ''}${yMil}`);
  }
  lines.push('999');
  return lines.join('\n');
}
