function toGerberCoord(mm: number): string {
  return String(Math.round(mm * 10000));
}

export interface GerberFileSet {
  files: Record<string, string>;
}

/** Generates a full manufacturing package (Gerber RS-274X/X2, Excellon, Pick&Place, IPC-D-356, DXF, 1:1 SVG). */
export function exportGerberSet(pcb: PcbProject, x2Attributes = true): GerberFileSet {
  const files: Record<string, string> = {};
  const name = pcb.projectName.replace(/[^A-Za-z0-9А-Яа-я_-]/g, '_') || 'board';

  const copperLayers: PcbLayerId[] =
    pcb.layerCount === 4
      ? ['TopCopper', 'Inner1', 'Inner2', 'BottomCopper']
      : ['TopCopper', 'BottomCopper'];

  const allLayers: { layer: PcbLayerId; ext: string; fn: string }[] = [
    ...copperLayers.map((l) => ({
      layer: l,
      ext: l === 'TopCopper' ? 'GTL' : l === 'BottomCopper' ? 'GBL' : l === 'Inner1' ? 'G2L' : 'G3L',
      fn: l === 'TopCopper' ? 'Copper,L1,Top' : l === 'BottomCopper' ? `Copper,L${pcb.layerCount},Bot` : l === 'Inner1' ? 'Copper,L2,Inr' : 'Copper,L3,Inr'
    })),
    { layer: 'TopMask', ext: 'GTS', fn: 'Soldermask,Top' },
    { layer: 'BottomMask', ext: 'GBS', fn: 'Soldermask,Bot' },
    { layer: 'TopSilk', ext: 'GTO', fn: 'Legend,Top' },
    { layer: 'BottomSilk', ext: 'GBO', fn: 'Legend,Bot' },
    { layer: 'TopPaste', ext: 'GTP', fn: 'Paste,Top' },
    { layer: 'BottomPaste', ext: 'GBP', fn: 'Paste,Bot' },
    { layer: 'BoardOutline', ext: 'GKO', fn: 'Profile,NP' }
  ];

  for (const item of allLayers) {
    files[`${name}.${item.ext}`] = generateLayerGerber(pcb, item.layer, item.fn, x2Attributes);
  }

  files[`${name}.drl`] = exportExcellonDrill(pcb);
  files[`${name}_PickAndPlace.csv`] = exportPickAndPlaceCsv(pcb);
  files[`${name}_IPC-D-356.ipc`] = exportIpcD356(pcb);
  files[`${name}.dxf`] = exportPcbDxf(pcb);
  files[`${name}_Top_1to1.svg`] = exportPcbSvg1to1(pcb, 'TopCopper', false);
  files[`${name}_Bottom_1to1_Mirror.svg`] = exportPcbSvg1to1(pcb, 'BottomCopper', true);

  return { files };
}

function generateLayerGerber(pcb: PcbProject, layer: PcbLayerId, x2Func: string, x2: boolean): string {
  const lines: string[] = [
    `G04 Generated by GOSTTrace EDA (ГОСТ-Трейс) *`,
    `%FSLAX34Y34*%`,
    `%MOMM*%`,
    `%LPD*%`,
    `G01*`
  ];
  if (x2) {
    lines.push(`%TF.GenerationSoftware,GOSTTrace,EDA,2.0*%`);
    lines.push(`%TF.FileFunction,${x2Func}*%`);
  }

  const apertures = new Map<string, number>();
  let nextD = 10;
  const macrosAdded = new Set<string>();
  const ensureRotRectMacro = () => {
    if (!macrosAdded.has('ROTRECT')) {
      macrosAdded.add('ROTRECT');
      lines.push('%AMROTRECT*21,1,$1,$2,0,0,$3*%');
    }
  };
  const getAper = (key: string, decl: string): number => {
    if (!apertures.has(key)) {
      const code = nextD++;
      apertures.set(key, code);
      lines.push(`%ADD${code}${decl}*%`);
    }
    return apertures.get(key)!;
  };

  const bodyLines: string[] = [];

  if (layer === 'BoardOutline') {
    const d = getAper('C_0.2', 'C,0.2000');
    bodyLines.push(`D${d}*`);
    const drawPoly = (pts: Point2D[]) => {
      if (pts.length < 2) return;
      bodyLines.push(`X${toGerberCoord(pts[0].x)}Y${toGerberCoord(pts[0].y)}D02*`);
      for (let i = 1; i <= pts.length; i++) {
        const p = pts[i % pts.length];
        bodyLines.push(`X${toGerberCoord(p.x)}Y${toGerberCoord(p.y)}D01*`);
      }
    };
    drawPoly(pcb.boardOutline);
    for (const cut of pcb.cutouts) drawPoly(cut.points);
  }

  const pads = getWorldPads(pcb);
  for (const wp of pads) {
    const isCopperMatch =
      (layer === 'TopCopper' && (wp.effectiveLayer === 'TopCopper' || wp.effectiveLayer === 'All')) ||
      (layer === 'BottomCopper' && (wp.effectiveLayer === 'BottomCopper' || wp.effectiveLayer === 'All')) ||
      ((layer === 'Inner1' || layer === 'Inner2') && wp.effectiveLayer === 'All');
    const isMaskMatch =
      (layer === 'TopMask' && (wp.effectiveLayer === 'TopCopper' || wp.effectiveLayer === 'All')) ||
      (layer === 'BottomMask' && (wp.effectiveLayer === 'BottomCopper' || wp.effectiveLayer === 'All'));
    const isPasteMatch =
      (layer === 'TopPaste' && wp.effectiveLayer === 'TopCopper') ||
      (layer === 'BottomPaste' && wp.effectiveLayer === 'BottomCopper');

    if (!isCopperMatch && !isMaskMatch && !isPasteMatch) continue;
    const expand = isMaskMatch ? (wp.pad.solderMaskExpansion ?? 0.1) : isPasteMatch ? (wp.pad.pasteMaskExpansion ?? 0) : 0;
    const rawW = Math.max(0.05, wp.pad.width + expand);
    const rawH = Math.max(0.05, wp.pad.height + expand);
    const normAng = ((wp.padAngleDeg % 360) + 360) % 360;

    let d: number;
    if (wp.pad.shape === 'Round') {
      const dia = Math.max(rawW, rawH);
      d = getAper(`C_${dia.toFixed(3)}`, `C,${dia.toFixed(4)}`);
    } else if (wp.pad.shape === 'Oval') {
      const swap = Math.abs((normAng % 180) - 90) < 1;
      const w = swap ? rawH : rawW;
      const h = swap ? rawW : rawH;
      d = getAper(`O_${w.toFixed(3)}_${h.toFixed(3)}`, `O,${w.toFixed(4)}X${h.toFixed(4)}`);
    } else if (Math.abs(normAng % 90) < 0.5) {
      const swap = Math.abs((normAng % 180) - 90) < 1;
      const w = swap ? rawH : rawW;
      const h = swap ? rawW : rawH;
      d = getAper(`R_${w.toFixed(3)}_${h.toFixed(3)}`, `R,${w.toFixed(4)}X${h.toFixed(4)}`);
    } else {
      ensureRotRectMacro();
      d = getAper(
        `RR_${rawW.toFixed(3)}_${rawH.toFixed(3)}_${normAng.toFixed(1)}`,
        `ROTRECT,${rawW.toFixed(4)}X${rawH.toFixed(4)}X${normAng.toFixed(2)}`
      );
    }
    bodyLines.push(`D${d}*`);
    bodyLines.push(`X${toGerberCoord(wp.x)}Y${toGerberCoord(wp.y)}D03*`);
  }

  if (layer === 'TopCopper' || layer === 'BottomCopper' || layer === 'Inner1' || layer === 'Inner2' || layer === 'TopMask' || layer === 'BottomMask') {
    for (const v of pcb.vias) {
      if (!isViaOnCamLayer(v, layer, pcb.layerCount)) continue;
      const dia = v.outerDiameter + (layer.includes('Mask') ? 0.1 : 0);
      const d = getAper(`C_${dia.toFixed(3)}`, `C,${dia.toFixed(4)}`);
      bodyLines.push(`D${d}*`);
      bodyLines.push(`X${toGerberCoord(v.x)}Y${toGerberCoord(v.y)}D03*`);
    }
  }

  for (const tr of pcb.traces) {
    if (tr.layer !== layer || tr.points.length < 2) continue;
    const d = getAper(`C_${tr.width.toFixed(3)}`, `C,${tr.width.toFixed(4)}`);
    bodyLines.push(`D${d}*`);
    bodyLines.push(`X${toGerberCoord(tr.points[0].x)}Y${toGerberCoord(tr.points[0].y)}D02*`);
    for (let i = 1; i < tr.points.length; i++) {
      bodyLines.push(`X${toGerberCoord(tr.points[i].x)}Y${toGerberCoord(tr.points[i].y)}D01*`);
    }
  }

  for (const pour of pcb.copperPours) {
    if (pour.layer !== layer || !pour.poured || !pour.computedIslands) continue;
    for (const isl of pour.computedIslands) {
      if (isl.outer.length < 3) continue;
      bodyLines.push(`G36*`);
      bodyLines.push(`X${toGerberCoord(isl.outer[0].x)}Y${toGerberCoord(isl.outer[0].y)}D02*`);
      for (let i = 1; i <= isl.outer.length; i++) {
        const pt = isl.outer[i % isl.outer.length];
        bodyLines.push(`X${toGerberCoord(pt.x)}Y${toGerberCoord(pt.y)}D01*`);
      }
      bodyLines.push(`G37*`);
    }
  }

  if (layer === 'TopSilk' || layer === 'BottomSilk') {
    const targetSide = layer === 'TopSilk' ? 'Top' : 'Bottom';
    const d = getAper('C_0.15', 'C,0.1500');
    bodyLines.push(`D${d}*`);
    for (const comp of pcb.components) {
      if (comp.side !== targetSide) continue;
      const mirror = comp.side === 'Bottom';
      for (const g of comp.graphics) {
        if (g.layer !== 'TopSilk') continue;
        if (g.type === 'line') {
          const p1 = transformPoint(g.x1, g.y1, comp.x, comp.y, comp.angle, mirror);
          const p2 = transformPoint(g.x2, g.y2, comp.x, comp.y, comp.angle, mirror);
          bodyLines.push(`X${toGerberCoord(p1.x)}Y${toGerberCoord(p1.y)}D02*`);
          bodyLines.push(`X${toGerberCoord(p2.x)}Y${toGerberCoord(p2.y)}D01*`);
        } else if (g.type === 'rect') {
          const pts = [
            transformPoint(g.x, g.y, comp.x, comp.y, comp.angle, mirror),
            transformPoint(g.x + g.w, g.y, comp.x, comp.y, comp.angle, mirror),
            transformPoint(g.x + g.w, g.y + g.h, comp.x, comp.y, comp.angle, mirror),
            transformPoint(g.x, g.y + g.h, comp.x, comp.y, comp.angle, mirror)
          ];
          bodyLines.push(`X${toGerberCoord(pts[0].x)}Y${toGerberCoord(pts[0].y)}D02*`);
          for (let i = 1; i <= 4; i++) {
            const pt = pts[i % 4];
            bodyLines.push(`X${toGerberCoord(pt.x)}Y${toGerberCoord(pt.y)}D01*`);
          }
        } else if (g.type === 'circle') {
          const c = transformPoint(g.cx, g.cy, comp.x, comp.y, comp.angle, mirror);
          const segs = 16;
          for (let s = 0; s <= segs; s++) {
            const a = (s / segs) * Math.PI * 2;
            bodyLines.push(`X${toGerberCoord(c.x + Math.cos(a) * g.r)}Y${toGerberCoord(c.y + Math.sin(a) * g.r)}D0${s === 0 ? 2 : 1}*`);
          }
        } else if (g.type === 'polyline' && g.points.length >= 2) {
          const pts = g.points.map((pt) => transformPoint(pt.x, pt.y, comp.x, comp.y, comp.angle, mirror));
          bodyLines.push(`X${toGerberCoord(pts[0].x)}Y${toGerberCoord(pts[0].y)}D02*`);
          for (let i = 1; i < pts.length; i++) bodyLines.push(`X${toGerberCoord(pts[i].x)}Y${toGerberCoord(pts[i].y)}D01*`);
          if (g.closed) bodyLines.push(`X${toGerberCoord(pts[0].x)}Y${toGerberCoord(pts[0].y)}D01*`);
        }
      }
      if (comp.showRefDes !== false && comp.refDes) {
        emitRefDesSilkStrokes(comp, mirror, bodyLines);
      }
    }
  }

  for (const sh of pcb.shapes) {
    if (sh.layer !== layer) continue;
    const aperCode = getAper(`C_${(sh.width || 0.2).toFixed(2)}`, `C,${(sh.width || 0.2).toFixed(4)}`);
    bodyLines.push(`D${aperCode}*`);
    if (sh.type === 'line' && sh.x2 !== undefined && sh.y2 !== undefined) {
      bodyLines.push(`X${toGerberCoord(sh.x1)}Y${toGerberCoord(sh.y1)}D02*`);
      bodyLines.push(`X${toGerberCoord(sh.x2)}Y${toGerberCoord(sh.y2)}D01*`);
    } else if (sh.type === 'circle' && sh.r) {
      for (let s = 0; s <= 16; s++) {
        const a = (s / 16) * Math.PI * 2;
        bodyLines.push(`X${toGerberCoord(sh.x1 + Math.cos(a) * sh.r)}Y${toGerberCoord(sh.y1 + Math.sin(a) * sh.r)}D0${s === 0 ? 2 : 1}*`);
      }
    }
  }

  return [...lines, ...bodyLines, 'M02*'].join('\n');
}

