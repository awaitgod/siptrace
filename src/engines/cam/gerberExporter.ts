function emitRefDesSilkStrokes(comp: PcbProject['components'][0], mirror: boolean, bodyLines: string[]): void {
  const ch = 1.0, cw = 0.65, gap = 0.25;
  const label = comp.refDes.toUpperCase();
  const totalW = label.length * (cw + gap) - gap;
  const oxBase = (comp.refDesOffset?.x ?? 0) - totalW * 0.5;
  const oyBase = (comp.refDesOffset?.y ?? 0) - ch * 0.5;
  for (let ci = 0; ci < label.length; ci++) {
    const strokes = SILK_GLYPHS[label[ci]];
    if (!strokes) continue;
    const xOff = oxBase + ci * (cw + gap);
    for (const st of strokes) {
      for (let si = 0; si < st.length; si++) {
        const p = transformPoint(xOff + st[si][0] * cw, oyBase + st[si][1] * ch, comp.x, comp.y, comp.angle, mirror);
        bodyLines.push(`X${toGerberCoord(p.x)}Y${toGerberCoord(p.y)}D0${si === 0 ? 2 : 1}*`);
      }
    }
  }
}
